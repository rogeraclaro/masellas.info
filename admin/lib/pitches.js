// Recruiter pages ("for…"): /per-a/<id>/, one private page per pitch, in one language. Each is that
// language's projects list page with the company in the heading, a short intro and only the chosen
// projects (of either collection, in the chosen order), carried in the page itself
// (<script id="projects-data">): no JSON file, no hreflang, no switcher, noindex, not in any sitemap.
// The detail opens as on the list, with <path>?p=<id> links (no per-project pages here).
// The id ends in random characters, so a page cannot be found from the company's name.
// Rewritten after every pitches, projects or glossary save (and at boot); like seo-pages.js, it only
// writes or deletes /per-a/<id>/index.html where that directory is free or holds a page it marked.
import { readFile, readdir, mkdir, unlink, rmdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import path from 'node:path';
import { writeAtomic } from './store.js';
import { LANGS, DEFAULT_LANG, localizedFile } from './languages.js';
import { parseRichText, richTextPlain } from './rich-text.js';
import { richTextHtml, escapeHtml } from './rich-text-html.js';
import { slugify } from './slug.js';
import { SITE, LIST, LD, format, pageStrings, webRootOf, ownership } from './seo-pages.js';

export const PITCH_DIR = 'per-a';
export const PITCH_PAGE_MARK = '<!-- generated by admin/lib/pitches.js: recruiter page';
export const pitchesPath = (dataFile) => path.join(path.dirname(dataFile), 'pitches.json');
export const PITCH_LIMITS = { pitches: 100, company: 60, intro: 1000, projects: 20 };

const COLLECTIONS = ['projects', 'projects-ac'];
const SLUG = '[a-z0-9]+(?:-[a-z0-9]+)*';
const ID = new RegExp(`^${SLUG}$`);
const REF = new RegExp(`^(${COLLECTIONS.join('|')})/(${SLUG})$`); // "<collection>/<project id>"
const prefix = (lang) => (lang === DEFAULT_LANG ? '/' : `/${lang}/`);
const pitchPath = (id) => `/${PITCH_DIR}/${id}/`;

// "Ça Va Bé, S.L." -> "ca-va-be-s-l-k3x9q2": readable, but the end cannot be guessed.
export function newPitchId(company, random = () => randomBytes(6).toString('hex')) {
  const base = slugify(company).slice(0, 40).replace(/-+$/, '');
  const tail = BigInt(`0x${random()}`).toString(36).slice(-6).padStart(6, '0');
  return `${base}-${tail}`;
}

/* ---------- validation ---------- */

// { pitches: [{ id, company, lang, intro, projects: ["<collection>/<id>", …] }] }. A pitch without an
// id is new and gets one (makeId). Errors are keyed "pitches.<index>.<field>".
export function validatePitches(input, { makeId = newPitchId } = {}) {
  if (input === null || typeof input !== 'object' || !Array.isArray(input.pitches)) {
    return { value: {}, errors: { _body: 'expected { pitches: [...] }' } };
  }
  if (input.pitches.length > PITCH_LIMITS.pitches) return { value: {}, errors: { _body: `up to ${PITCH_LIMITS.pitches} pitches` } };
  const errors = {};
  const seen = new Set();
  const pitches = input.pitches.map((raw, index) => {
    const fail = (field, message) => { errors[`pitches.${index}.${field}`] = message; };
    const item = raw !== null && typeof raw === 'object' ? raw : {};
    const company = typeof item.company === 'string' ? item.company.trim() : '';
    if (!company) fail('company', 'company is required');
    else if (company.length > PITCH_LIMITS.company) fail('company', `company must be ${PITCH_LIMITS.company} characters or fewer`);

    let id = typeof item.id === 'string' ? item.id.trim() : '';
    if (!id) id = makeId(company || 'pitch');
    else if (!ID.test(id) || id.length > 60) fail('id', 'id must be a url slug (a-z, 0-9, single hyphens)');
    if (seen.has(id)) fail('id', `id "${id}" is used twice`);
    seen.add(id);

    const lang = item.lang;
    if (!LANGS.includes(lang)) fail('lang', 'language must be ca, en or es');

    const intro = typeof item.intro === 'string' ? item.intro.trim() : '';
    if (intro.length > PITCH_LIMITS.intro) fail('intro', `intro must be ${PITCH_LIMITS.intro} characters or fewer`);
    else if (intro && parseRichText(intro).errors.length) fail('intro', `intro: ${parseRichText(intro).errors.join(' ')}`);

    const projects = Array.isArray(item.projects) ? item.projects : [];
    if (!projects.length) fail('projects', 'choose at least one project');
    else if (projects.length > PITCH_LIMITS.projects) fail('projects', `up to ${PITCH_LIMITS.projects} projects`);
    else if (!projects.every((ref) => typeof ref === 'string' && REF.test(ref))) fail('projects', 'unknown project reference');
    else if (new Set(projects).size !== projects.length) fail('projects', 'a project is chosen twice');

    return { id, company, lang, intro, projects };
  });
  return { value: Object.keys(errors).length ? {} : { pitches }, errors };
}

/* ---------- one page ---------- */

const between = (html, [start, end]) => html.replace(new RegExp(`${start}[\\s\\S]*?${end}`), `${start}${end}`);
const jsonScript = (id, value) => `<script type="application/json" id="${id}">${JSON.stringify(value).replace(/</g, '\\u003c')}</script>`;

// listHtml: the projects list page of the pitch's language (as in the web root). projects: the public
// projects to show, in order, each with its `collection`. aiHeadings: { <collection>: the detail's
// "how I used AI" / "how it was made" heading in that language }. Returns the page, or null when the
// list page lacks a part it edits.
export function pitchPage(listHtml, { pitch, projects, aiHeadings }) {
  const strings = pageStrings(listHtml);
  if (!strings || !['pitch_heading', 'pitch_title', 'pitch_detail_title'].every((key) => typeof strings[key] === 'string')) return null;
  const heading = format(strings.pitch_heading, { company: pitch.company });
  const title = format(strings.pitch_title, { company: pitch.company });
  const url = `${SITE}${pitchPath(pitch.id)}`;
  const intro = pitch.intro ? richTextPlain(pitch.intro).slice(0, 200) : '';
  const image = projects.find((project) => project.thumbs?.length)?.thumbs[0];

  let html = listHtml;
  let complete = true;
  const edit = (pattern, replace) => {
    if (complete && pattern.test(html)) html = html.replace(pattern, replace);
    else complete = false;
  };

  edit(/<title>[^<]*<\/title>/, () => `<title>${escapeHtml(title)}</title>\n\t<meta name="robots" content="noindex, nofollow">`);
  edit(/<meta name="description" content="[^"]*">/, (tag) => (intro ? `<meta name="description" content="${escapeHtml(intro)}">` : tag));
  edit(/<link rel="canonical" href="[^"]*">/, () => `<link rel="canonical" href="${url}">`);
  edit(/\s*<link rel="alternate" hreflang="[^"]*" href="[^"]*">(?:\s*<link rel="alternate" hreflang="[^"]*" href="[^"]*">)*/, () => '');
  edit(/<meta property="og:title" content="[^"]*">/, () => `<meta property="og:title" content="${escapeHtml(title)}">`);
  edit(/<meta property="og:description" content="[^"]*">/, (tag) => (intro ? `<meta property="og:description" content="${escapeHtml(intro)}">` : tag));
  edit(/<meta property="og:url" content="[^"]*">/, () => `<meta property="og:url" content="${url}">`);
  edit(/<meta property="og:image" content="[^"]*">/, (tag) => (image ? `<meta property="og:image" content="${escapeHtml(new URL(image, SITE).href)}">` : tag));
  edit(/\s*<nav class="lang-nav"[\s\S]*?<\/nav>/, () => '');
  edit(/<body>/, () => '<body data-ask>'); // "ask me" (js/shared/ask.js)
  edit(/(<h1 class="page-title" data-split>)[^<]*(<\/h1>)/, (whole, open, close) => `${open}${escapeHtml(heading)}${close}`
    + (pitch.intro ? `\n\t\t<div class="page-intro rich-text">${richTextHtml(pitch.intro)}</div>` : ''));
  edit(/(<ul class="work-list" id="projects-list"[^>]*?) data-collection="[^"]*" data-list-path="[^"]*" data-list-title="[^"]*">/,
    (whole, open) => `${open} data-collection="" data-list-path="${pitchPath(pitch.id)}" data-list-title="${escapeHtml(title)}" data-detail-links="query">`);
  edit(/(<p class="detail__crumb">)[^<]*(<\/p>)/, (whole, open, close) => `${open}${escapeHtml(heading)}${close}`);
  edit(/<script type="application\/json" id="i18n">[\s\S]*?<\/script>/, () => [
    jsonScript('projects-data', { projects: projects.map(({ collection, ...project }) => ({ ...project, aiHeading: aiHeadings[collection] ?? '' })) }),
    jsonScript('i18n', { ...strings, detail_title: strings.pitch_detail_title }),
  ].join('\n'));
  if (!complete) return null;

  html = between(between(html, LIST), LD).replace(/ aria-current="page"/g, ''); // no crawler copies; no menu tab is this page
  return `${PITCH_PAGE_MARK} for ${pitch.company.replace(/--/g, '- -')} (rewritten on every save, removed with the pitch) -->\n${html}`;
}

/* ---------- files ---------- */

const decode = (text) => text.replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
const aiHeadingOf = (html) => decode(/<h3 class="detail__heading" id="detail-ai-heading">([^<]*)<\/h3>/.exec(html ?? '')?.[1] ?? '');

async function readOptional(file) {
  try {
    return await readFile(file, 'utf8');
  } catch (err) {
    if (err.code === 'ENOENT') return null;
    throw err;
  }
}

// Never throws: a missing page or data file, or a failed write, is logged and that pitch skipped.
export async function writePitchPages({ publicFile, pitches, log = console.error }) {
  const root = webRootOf(publicFile);
  if (!root || !existsSync(path.join(root, 'index.html'))) {
    if (pitches.length) log(`admin: recruiter pages skipped: PUBLIC_FILE (${publicFile}) is not in <web root>/projects/data/`);
    return;
  }
  const dir = path.join(root, PITCH_DIR);
  const dataDir = path.dirname(publicFile);
  const written = new Set();
  for (const pitch of pitches) {
    const target = path.join(dir, pitch.id);
    try {
      const pages = {};
      const lists = {};
      for (const collection of COLLECTIONS) {
        pages[collection] = await readOptional(path.join(root, prefix(pitch.lang), collection, 'index.html'));
        const json = await readOptional(localizedFile(path.join(dataDir, `${collection}.json`), pitch.lang));
        lists[collection] = json ? JSON.parse(json).projects : [];
      }
      const projects = [];
      for (const ref of pitch.projects) {
        const [collection, id] = ref.split('/');
        const found = lists[collection].find((project) => project.id === id);
        if (found) projects.push({ ...found, collection });
        else log(`admin: ${pitch.id}: ${ref} is not public in ${pitch.lang}, left out`);
      }
      const html = pages.projects && pitchPage(pages.projects, {
        pitch, projects, aiHeadings: Object.fromEntries(COLLECTIONS.map((collection) => [collection, aiHeadingOf(pages[collection])])),
      });
      if (!html) {
        log(`admin: ${target}/ not written: the ${pitch.lang} projects page is missing or lacks a part`);
        continue;
      }
      if ((await ownership(target, PITCH_PAGE_MARK)) === 'other') {
        log(`admin: ${target}/ not written: it exists and is not the admin's`);
        continue;
      }
      await mkdir(target, { recursive: true });
      await writeAtomic(path.join(target, 'index.html'), html, 0o644);
      written.add(pitch.id);
    } catch (err) {
      log(`admin: ${target}/ not written: ${err.message}`);
    }
  }
  // Pages of pitches that are gone.
  const keep = new Set(pitches.map((pitch) => pitch.id));
  let entries = [];
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch (err) {
    if (err.code !== 'ENOENT') log(`admin: old recruiter pages not removed: ${err.message}`);
  }
  for (const entry of entries) {
    if (!entry.isDirectory() || keep.has(entry.name) || !ID.test(entry.name)) continue;
    const target = path.join(dir, entry.name);
    try {
      if ((await ownership(target, PITCH_PAGE_MARK)) !== 'owned') continue;
      await unlink(path.join(target, 'index.html'));
      await rmdir(target);
    } catch (err) {
      log(`admin: ${target}/ not removed: ${err.message}`);
    }
  }
  return written;
}

// Copies of the public projects for crawlers that do not run JS: the rows and a JSON-LD ItemList inside
// the markers of each projects page in the web root, one page per project and language
// (<collection dir>/<id>/index.html: the list page with that project's head and detail filled in),
// /sitemap-projects.xml and /llms.txt. Rewritten after every publish of a projects collection (and at
// boot); the page script swaps the rows (and the detail) for its own once its data loads.
// Never throws: a missing page, a page without markers or a failed write is logged and skipped.
// It only ever writes or deletes <collection dir>/<id>/index.html (and that directory when it is left
// empty) for slug ids, and only where the directory is free or holds a page it marked (PROJECT_PAGE_MARK).
import { readFile, readdir, lstat, mkdir, unlink, rmdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { writeAtomic } from './store.js';
import { LANGS, DEFAULT_LANG, localizedFile } from './languages.js';
import { richTextPlain } from './rich-text.js';
import { richTextHtml, escapeHtml } from './rich-text-html.js';
import { checkSlug } from './slug.js';

// These mirror scripts/build-pages.mjs and i18n/en.json (checked by test/seo-pages.test.js): the admin is
// deployed without them.
export const SITE = 'https://masellas.info';
export const DESCRIPTION = 'Roger Masellas: web projects since 1996, AI-assisted development (Claude Code) and teaching web technologies.'; // i18n/en.json home.description
const COLLECTIONS = [
  { name: 'projects', label: 'projects (IA)' },
  { name: 'projects-ac', label: 'projects (B.C.)' },
];
const prefix = (lang) => (lang === DEFAULT_LANG ? '/' : `/${lang}/`);
const pageUrl = (collection, lang) => `${SITE}${prefix(lang)}${collection}/`;
export const PAGES = [{ name: '', label: 'home' }, ...COLLECTIONS]
  .flatMap(({ name, label }) => LANGS.map((lang) => ({ label: `${label} (${lang})`, url: `${SITE}${prefix(lang)}${name ? `${name}/` : ''}` })));

const LIST = ['<!-- projects:start -->', '<!-- projects:end -->'];
const LD = ['<!-- projects-ld:start -->', '<!-- projects-ld:end -->'];
// First line of every project page: what marks a directory as the admin's (to rewrite or remove).
export const PROJECT_PAGE_MARK = '<!-- generated by admin/lib/seo-pages.js: project page';

// The page of project `id` in a list at `url` (absolute): <list path><id>/, or the legacy
// <list path>?p=<id> when it has no page (hasPage false). Root-absolute, so it works from a project page.
function projectHref(url, id, hasPage) {
  const listPath = new URL(url).pathname;
  return hasPage(id) ? `${listPath}${encodeURIComponent(id)}/` : `${listPath}?p=${encodeURIComponent(id)}`;
}
const projectUrl = (collection, lang, id) => `${pageUrl(collection, lang)}${encodeURIComponent(id)}/`;
const always = () => true;

// Same classes as the rows the page script builds; data-static lets the CSS hide them until it swaps them.
const row = (project, href) => `<li data-category="${escapeHtml(project.category)}"><a class="work-item" href="${escapeHtml(href)}" data-static>`
  + `<span class="work-item__title">${escapeHtml(project.title)}</span> <span class="work-item__meta">${escapeHtml(project.category)} / ${escapeHtml(project.year)}</span> `
  + `<span class="work-item__desc">${escapeHtml(project.description)}</span></a></li>`;

function creativeWork(project, url, hasPage = always) {
  const work = { '@type': 'CreativeWork', name: project.title, description: project.description, url: new URL(projectHref(url, project.id, hasPage), url).href };
  if (project.year !== '' && project.year != null) work.dateCreated = String(project.year);
  if (project.tools?.length) work.keywords = project.tools.join(', ');
  if (project.thumbs?.length) work.image = new URL(project.thumbs[0], url).href;
  const text = richTextPlain(project.ai ?? '');
  if (text) work.text = text;
  return Object.fromEntries(Object.entries(work).filter(([, value]) => value !== ''));
}

// "<" escaped so no text can close the <script>.
const ldScript = (ld) => `<script type="application/ld+json">${JSON.stringify(ld).replace(/</g, '\\u003c')}</script>`;
const markerPattern = ([start, end]) => new RegExp(`${start}[\\s\\S]*?${end}`);
const between = (html, markers, content) => html.replace(markerPattern(markers), () => `${markers[0]}${content}${markers[1]}`);
const hasMarkers = (html) => [...LIST, ...LD].every((marker) => html.includes(marker));

// The page HTML with both marker pairs filled (any earlier content replaced), or null if one is missing.
// hasPage(id): whether the project has its own page (default: all do).
export function injectProjects(html, projects, url, hasPage = always) {
  if (!hasMarkers(html)) return null;
  const ld = {
    '@context': 'https://schema.org',
    '@type': 'ItemList',
    url,
    numberOfItems: projects.length,
    itemListElement: projects.map((project, index) => ({ '@type': 'ListItem', position: index + 1, item: creativeWork(project, url, hasPage) })),
  };
  const rows = projects.map((project) => row(project, projectHref(url, project.id, hasPage))).join('\n');
  return between(between(html, LD, ldScript(ld)), LIST, rows ? `\n${rows}\n` : '');
}

/* ---------- one project page ---------- */

const format = (template, params) => template.replace(/\{(\w+)\}/g, (whole, name) => (Object.hasOwn(params, name) ? String(params[name]) : whole));

// The UI strings the build put in the page (<script id="i18n">, see js/shared/i18n.js), or null.
function pageStrings(html) {
  const match = /<script type="application\/json" id="i18n">([\s\S]*?)<\/script>/.exec(html);
  try {
    return match ? JSON.parse(match[1]) : null;
  } catch {
    return null;
  }
}

function httpUrl(value) {
  try {
    const url = new URL(value);
    return /^https?:$/.test(url.protocol) ? url.href : null;
  } catch {
    return null;
  }
}

// Same markup as the page script's detail (renderDetail in projects/js/projects.js).
function aiHtml(text) {
  try {
    return richTextHtml(text, { linkClass: 'detail-link detail-link--inline', headingTag: 'h4' });
  } catch {
    return `<p>${escapeHtml(text)}</p>`; // published text is validated; never fail a page over it
  }
}

const literal = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// Project page: the (injected) list page of the same collection and language, with the project's
// <head> (title in the page's detail_title format, description, canonical, hreflang alternates to the
// languages in `langs`, og:*, a CreativeWork JSON-LD between the projects-ld markers), the language
// switcher pointing at those siblings, and #detail filled in (still hidden: the script opens it).
// next: the next project in the list (null for a list of one). Returns null if the page lacks a part.
export function projectPage(listHtml, { collection, lang, project, next, langs, hasPage = always }) {
  const strings = pageStrings(listHtml);
  if (!strings || !['detail_title', 'next', 'visit_label'].every((key) => typeof strings[key] === 'string')) return null;
  const listUrl = pageUrl(collection, lang);
  const url = projectUrl(collection, lang, project.id);
  const title = escapeHtml(project.title);
  const description = project.description ? escapeHtml(project.description) : '';
  const visit = httpUrl(project.url);
  const ai = typeof project.ai === 'string' ? project.ai.trim() : '';
  const tools = Array.isArray(project.tools) ? project.tools : [];
  const hidden = (show) => (show ? '' : ' hidden');

  let html = listHtml;
  let complete = true;
  // Each part must be found exactly where the build puts it; otherwise the page is not written.
  const edit = (pattern, replace) => {
    if (complete && pattern.test(html)) html = html.replace(pattern, replace);
    else complete = false;
  };

  edit(/<title>[^<]*<\/title>/, () => `<title>${escapeHtml(format(strings.detail_title, { title: project.title }))}</title>`);
  edit(/<meta name="description" content="[^"]*">/, (tag) => (description ? `<meta name="description" content="${description}">` : tag));
  edit(/<link rel="canonical" href="[^"]*">/, () => `<link rel="canonical" href="${url}">`);
  const alternates = [...langs.map((code) => [code, projectUrl(collection, code, project.id)]), ...(langs.includes(DEFAULT_LANG) ? [['x-default', projectUrl(collection, DEFAULT_LANG, project.id)]] : [])];
  edit(/<link rel="alternate" hreflang="[^"]*" href="[^"]*">(?:\s*<link rel="alternate" hreflang="[^"]*" href="[^"]*">)*/,
    () => alternates.map(([code, href]) => `<link rel="alternate" hreflang="${code}" href="${href}">`).join('\n\t'));
  const og = [
    `<meta property="og:title" content="${title}">`,
    ...(description ? [`<meta property="og:description" content="${description}">`] : []),
    `<meta property="og:url" content="${url}">`,
    ...(project.thumbs?.length ? [`<meta property="og:image" content="${escapeHtml(new URL(project.thumbs[0], SITE).href)}">`] : []),
  ];
  edit(markerPattern(LD), () => `${LD[0]}${[...og, ldScript({ '@context': 'https://schema.org', ...creativeWork(project, listUrl, hasPage) })].join('\n\t')}${LD[1]}`);
  for (const code of LANGS) {
    const listPath = `${prefix(code)}${collection}/`;
    edit(new RegExp(`href="${literal(listPath)}" hreflang="${code}"`), (attrs) => (langs.includes(code) ? `href="${listPath}${encodeURIComponent(project.id)}/" hreflang="${code}"` : attrs));
  }

  edit(/(<h2 class="page-title detail__title" id="detail-title"[^>]*>)<\/h2>/, (whole, open) => `${open}${title}</h2>`);
  edit(/(<p class="detail__meta"[^>]*>)<\/p>/, (whole, open) => `${open}${escapeHtml(project.category)} / ${escapeHtml(project.year)}</p>`);
  edit(/<p class="detail__lead"([^>]*)><\/p>/, (whole, attrs) => `<p class="detail__lead"${attrs}${hidden(description)}>${description}</p>`);
  edit(/<section class="detail__ai"([^>]*)>/, (whole, attrs) => `<section class="detail__ai"${attrs}${hidden(ai)}>`);
  edit(/(<div class="detail__body[^"]*"[^>]*>)<\/div>/, (whole, open) => `${open}${ai ? aiHtml(ai) : ''}</div>`);
  edit(/<ul class="detail__tools"([^>]*)><\/ul>/, (whole, attrs) => `<ul class="detail__tools"${attrs}${hidden(tools.length)}>${tools.map((tool) => `<li>${escapeHtml(tool)}</li>`).join('')}</ul>`);
  edit(/<p class="detail__visit"([^>]*)><a class="detail-link"([^>]*)>/, (whole, attrs, linkAttrs) => (visit
    ? `<p class="detail__visit"${attrs}><a class="detail-link"${linkAttrs} href="${escapeHtml(visit)}" aria-label="${escapeHtml(format(strings.visit_label, { title: project.title }))}">`
    : `<p class="detail__visit"${attrs} hidden><a class="detail-link"${linkAttrs}>`));
  edit(/<nav class="detail__next"([^>]*)>(<a class="detail-link detail-link--big" href=")[^"]*("><\/a>)/, (whole, attrs, open, close) => (next
    ? `<nav class="detail__next"${attrs}>${open}${escapeHtml(projectHref(listUrl, next.id, hasPage))}">${escapeHtml(format(strings.next, { title: next.title }))}</a>`
    : `<nav class="detail__next"${attrs} hidden>${open}${new URL(listUrl).pathname}${close}`));

  return complete ? `${PROJECT_PAGE_MARK} (rewritten on every publish, removed once the project is no longer public) -->\n${html}` : null;
}

// sitemap-projects.xml: every project page, each with its alternates (x-default = ca, when it has one).
// pages: { <collection>: { <lang>: [ids with a page] } }.
export function sitemapProjectsXml(pages) {
  const urls = [];
  for (const { name } of COLLECTIONS) {
    const byLang = pages[name] ?? {};
    const ids = [...new Set(LANGS.flatMap((lang) => byLang[lang] ?? []))];
    for (const id of ids) {
      const langs = LANGS.filter((lang) => (byLang[lang] ?? []).includes(id));
      const alternates = [...langs, ...(langs.includes(DEFAULT_LANG) ? ['x-default'] : [])]
        .map((code) => `\t\t<xhtml:link rel="alternate" hreflang="${code}" href="${escapeHtml(projectUrl(name, code === 'x-default' ? DEFAULT_LANG : code, id))}"/>`);
      for (const lang of langs) urls.push(['\t<url>', `\t\t<loc>${escapeHtml(projectUrl(name, lang, id))}</loc>`, ...alternates, '\t</url>'].join('\n'));
    }
  }
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">',
    ...urls,
    '</urlset>',
    '',
  ].join('\n');
}

// /llms.txt (llmstxt.org): the site, its pages, then every project of each collection in en.
// byCollection: { <collection name>: public en projects }. hasPage(collection, id): whether the en
// project has its own page (default: all do).
export function llmsText(byCollection, hasPage = always) {
  const lines = ['# Roger Masellas', '', `> ${DESCRIPTION}`, '', '## Pages', '', ...PAGES.map(({ label, url }) => `- [${label}](${url})`),
    `- [project pages (sitemap)](${SITE}/sitemap-projects.xml)`];
  for (const { name, label } of COLLECTIONS) {
    lines.push('', `## ${label}`);
    const listUrl = pageUrl(name, 'en');
    for (const project of byCollection[name] ?? []) {
      lines.push('', `### [${project.title}](${new URL(projectHref(listUrl, project.id, (id) => hasPage(name, id)), listUrl).href})`, '', `${project.year} / ${project.category}`);
      if (project.description) lines.push('', project.description);
      if (project.tools?.length) lines.push('', `Tools: ${project.tools.join(', ')}`);
      if (project.url) lines.push('', `Link: ${project.url}`);
      const ai = richTextPlain(project.ai ?? '');
      if (ai) lines.push('', ai);
    }
  }
  return `${lines.join('\n')}\n`;
}

/* ---------- files ---------- */

// PUBLIC_FILE is <web root>/projects/data/projects.json; anything else (e.g. a local scratch copy) has
// no pages next to it.
function webRootOf(publicFile) {
  const dataDir = path.dirname(publicFile);
  if (path.basename(dataDir) !== 'data' || path.basename(path.dirname(dataDir)) !== 'projects') return null;
  return path.dirname(path.dirname(dataDir));
}

async function readPublic(dataDir, collection, lang) {
  try {
    return JSON.parse(await readFile(localizedFile(path.join(dataDir, `${collection}.json`), lang), 'utf8')).projects;
  } catch (err) {
    if (err.code === 'ENOENT') return null;
    throw err;
  }
}

const isSlug = (id) => checkSlug(id).value === id;
const missing = (err) => err.code === 'ENOENT';

// <collection dir>/<id>/: 'free' (absent or an empty directory), 'owned' (a directory whose index.html
// is a regular file starting with PROJECT_PAGE_MARK) or 'other' (anything else, symlinks included).
async function ownership(dir) {
  let info;
  try {
    info = await lstat(dir);
  } catch (err) {
    if (missing(err)) return 'free';
    throw err;
  }
  if (!info.isDirectory()) return 'other';
  const index = path.join(dir, 'index.html');
  try {
    if (!(await lstat(index)).isFile()) return 'other';
  } catch (err) {
    if (missing(err)) return (await readdir(dir)).length ? 'other' : 'free';
    throw err;
  }
  return (await readFile(index, 'utf8')).startsWith(PROJECT_PAGE_MARK) ? 'owned' : 'other';
}

// The ids of `projects` that may have a page in `dir` (a slug, and a directory that is free or the admin's).
async function pageIds(dir, projects, log) {
  const ids = new Set();
  for (const { id } of projects) {
    if (!isSlug(id)) {
      log(`admin: no project page for ${JSON.stringify(id)} in ${dir}: the id is not a url slug`);
      continue;
    }
    const target = path.join(dir, id);
    try {
      if ((await ownership(target)) === 'other') log(`admin: ${target}/ not written: it exists and is not the admin's (no generated index.html)`);
      else ids.add(id);
    } catch (err) {
      log(`admin: ${target}/ not written: ${err.message}`);
    }
  }
  return ids;
}

// Removes the admin's pages (and their directory, when that leaves it empty) for ids not in `keep`.
async function prunePages(dir, keep, log) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch (err) {
    if (!missing(err)) log(`admin: old project pages in ${dir} not removed: ${err.message}`);
    return;
  }
  for (const entry of entries) {
    if (!entry.isDirectory() || !isSlug(entry.name) || keep.has(entry.name)) continue;
    const target = path.join(dir, entry.name);
    try {
      if ((await ownership(target)) !== 'owned') continue;
      await unlink(path.join(target, 'index.html'));
    } catch (err) {
      log(`admin: ${target}/index.html not removed: ${err.message}`);
      continue;
    }
    await rmdir(target).catch((err) => log(`admin: ${target}/ kept: ${err.message}`));
  }
}

export async function writeSeoFiles({ publicFile, log = console.error }) {
  const root = webRootOf(publicFile);
  if (!root || !existsSync(path.join(root, 'index.html'))) {
    log(`admin: crawler copies skipped: PUBLIC_FILE (${publicFile}) is not in <web root>/projects/data/`);
    return;
  }
  const dataDir = path.dirname(publicFile);
  const en = {};
  const written = {}; // { <collection>: { <lang>: [ids whose page was written] } }
  for (const { name } of COLLECTIONS) {
    written[name] = {};
    // First every language (its list, its page, which ids may have a page), so each page knows its siblings.
    const state = {};
    for (const lang of LANGS) {
      const dir = path.join(root, prefix(lang), name);
      const file = path.join(dir, 'index.html');
      try {
        const projects = await readPublic(dataDir, name, lang);
        if (lang === 'en') en[name] = projects;
        if (!projects) {
          log(`admin: ${file} not updated: no public ${name}.${lang}.json yet`);
          continue;
        }
        state[lang] = { dir, file, projects, page: null, ids: new Set() };
        if (!existsSync(file)) {
          log(`admin: ${file} not updated: the page is missing`);
          continue;
        }
        const page = await readFile(file, 'utf8');
        if (!hasMarkers(page)) {
          log(`admin: ${file} not updated: no projects markers`);
          continue;
        }
        state[lang].page = page;
        // A page the project pages cannot be built from (an older template) keeps the legacy ?p= links.
        if (projectPage(page, { collection: name, lang, project: { id: 'probe', title: '' }, next: null, langs: [] }) === null) {
          log(`admin: no project pages in ${dir}: ${file} has no project detail to fill`);
        } else {
          state[lang].ids = await pageIds(dir, projects, log);
        }
      } catch (err) {
        log(`admin: ${file} not updated: ${err.message}`);
      }
    }
    for (const [lang, { dir, file, projects, page, ids }] of Object.entries(state)) {
      if (page) {
        const hasPage = (id) => ids.has(id);
        const html = injectProjects(page, projects, pageUrl(name, lang), hasPage);
        try {
          await writeAtomic(file, html, 0o644);
        } catch (err) {
          log(`admin: ${file} not updated: ${err.message}`);
        }
        written[name][lang] = [];
        for (const [index, project] of projects.entries()) {
          if (!ids.has(project.id)) continue;
          const target = path.join(dir, project.id);
          const langs = LANGS.filter((code) => state[code]?.ids.has(project.id));
          const next = projects.length > 1 ? projects[(index + 1) % projects.length] : null;
          const out = projectPage(html, { collection: name, lang, project, next, langs, hasPage });
          try {
            if (out === null) throw new Error('the list page has no project detail to fill');
            await mkdir(target).catch((err) => {
              if (err.code !== 'EEXIST') throw err;
            });
            await writeAtomic(path.join(target, 'index.html'), out, 0o644);
            written[name][lang].push(project.id);
          } catch (err) {
            log(`admin: ${target}/index.html not written: ${err.message}`);
          }
        }
      }
      await prunePages(dir, new Set(projects.map((project) => project.id)), log);
    }
  }
  const files = [
    ['llms.txt', () => llmsText(en, (name, id) => (written[name].en ?? []).includes(id))],
    // Last: the deploy waits for it as the sign that this run has finished.
    ['sitemap-projects.xml', () => sitemapProjectsXml(written)],
  ];
  for (const [name, content] of files) {
    try {
      await writeAtomic(path.join(root, name), content(), 0o644);
    } catch (err) {
      log(`admin: ${path.join(root, name)} not updated: ${err.message}`);
    }
  }
}
